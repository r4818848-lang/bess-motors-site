import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import snapshot from "../src/data/meta-ads-2026-11-18.json";
import { metaAdsSnapshot, summarizeMetaAds, validateMetaAdsRows } from "../src/lib/meta-ads-costs";

const rows = validateMetaAdsRows(snapshot.rows);
const s = summarizeMetaAds(rows);
assert.equal(rows.length, 88);
assert.equal(s.spend, 4120.33);
assert.equal(s.leads, 71);
assert.equal(s.campaigns.length, 16);
assert.equal(s.campaigns.reduce((sum,c)=>Math.round((sum+c.spend)*100)/100,0), s.spend);
assert.equal(rows.every(r=>r.currency==="PLN"&&r.date>=snapshot.dateFrom&&r.date<=snapshot.dateTo),true);
assert.equal(new Set(rows.map(x=>[x.date,x.account_id,x.campaign_id].join(":"))).size,rows.length);
assert.equal(metaAdsSnapshot().mode,"snapshot");
assert.equal(metaAdsSnapshot().setupRequired,true);
assert.equal(metaAdsSnapshot(true).syncError,true);
assert.throws(()=>validateMetaAdsRows([...snapshot.rows,snapshot.rows[0]]),/duplicate_meta_day/);
assert.throws(()=>validateMetaAdsRows([{...snapshot.rows[0],currency:"USD"}]),/unexpected_currency/);
assert.equal(validateMetaAdsRows([{...snapshot.rows[0],account_id:"other_account"}]).length,0);
assert.throws(()=>validateMetaAdsRows([{...snapshot.rows[0],spend:-1}]),/invalid_meta_metric/);
const route=readFileSync("src/app/api/crm/meta-ads/route.ts","utf8");
assert.match(route,/verifyToken/);
assert.match(route,/session\.role !== "admin"/);
assert.match(route,/process\.env\.WINDSOR_API_KEY/);
assert.match(route,/Cache-Control":"private, no-store"/);
assert.match(route,/url\.searchParams\.set\("select_accounts"/);
assert.doesNotMatch(route,/NextResponse\.json\(.*apiKey/);
const panel=readFileSync("src/components/crm/MetaAdsCostPanel.tsx","utf8");
assert.match(panel,/report\.mode==="snapshot"/);
assert.match(panel,/report\.dateFrom/);
assert.match(panel,/loadDb\(\)/);
assert.match(panel,/getItem\("bess-jwt"\)/);
assert.match(panel,/ROAS/);
console.log("Meta Ads: Windsor daily snapshot 4,120.33 PLN / 71 reported leads, 16 campaigns; guarded API and report OK");
